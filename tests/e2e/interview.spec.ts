import {test,expect,type Page} from '@playwright/test'
async function openBank(page:Page){await page.getByRole('button',{name:'Phỏng vấn & Retry',exact:true}).click();await expect(page.getByRole('heading',{name:'Phỏng vấn & luyện lại'})).toBeVisible()}
async function chooseRole(page:Page){await page.getByRole('article').filter({has:page.getByRole('heading',{name:'Vai trò trong dự án',exact:true})}).getByRole('button',{name:'Luyện câu này'}).click()}
const original='私は画面の実装とAPI連携を担当しています。入力チェックとエラー表示を実装しました。'
async function answer(page:Page,text=original){await page.getByLabel('Câu trả lời tiếng Nhật (text)').fill(text);await page.getByRole('button',{name:'Gửi câu trả lời & xem feedback'}).click();await expect(page.getByRole('heading',{name:'Evidence Inspector'})).toBeVisible()}
test('text session -> exact evidence self-review -> guided/independent -> compare -> transcript edit invalidation -> reload',async({page})=>{
  await page.goto('/');await openBank(page);await chooseRole(page)
  await page.getByLabel('Câu trả lời tiếng Nhật (text)').fill(original)
  await expect(page.getByText('Đã lưu Interview trên thiết bị',{exact:true})).toBeVisible()
  await page.reload();await openBank(page);await page.getByRole('button',{name:'Lịch sử Interview',exact:true}).click()
  await page.getByRole('button',{name:'Tiếp tục bản nháp'}).click()
  await expect(page.getByLabel('Câu trả lời tiếng Nhật (text)')).toHaveValue(original)
  await page.getByRole('button',{name:'Gửi câu trả lời & xem feedback'}).click()
  await expect(page.getByRole('heading',{name:'Evidence Inspector'})).toBeVisible()
  await expect(page.getByTestId('interview-transcript')).toHaveText(original)
  await expect(page.getByText('Điểm tự đánh giá: N/A',{exact:true})).toBeVisible()
  await page.getByLabel('Trích dẫn chính xác từ transcript').fill('không có trong câu trả lời')
  await page.getByLabel('Giải thích điểm & việc cần sửa').fill('Cần cụ thể hơn.')
  await page.getByRole('button',{name:'Lưu tự đánh giá có chứng cứ'}).click()
  await expect(page.getByRole('alert')).toContainText('Trích dẫn phải xuất hiện chính xác')
  for(const id of ['intent','specificity','structure']){
    await page.getByLabel('Tiêu chí rubric').selectOption(id)
    await page.getByLabel('Trích dẫn chính xác từ transcript').fill(original)
    await page.getByLabel('Giải thích điểm & việc cần sửa').fill('Đã nêu việc cá nhân thực hiện, cần bổ sung kết quả thật.')
    await page.getByRole('combobox',{name:'Điểm tự đánh giá',exact:true}).selectOption('2')
    await page.getByRole('button',{name:'Lưu tự đánh giá có chứng cứ'}).click()
    await expect(page.getByRole('status').filter({hasText:'Đã lưu tự đánh giá có chứng cứ'})).toBeVisible()
  }
  await expect(page.getByText('Điểm tự đánh giá: 67 / 100',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Guided Retry',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Gợi ý Guided Retry'})).toBeVisible()
  await expect(page.getByLabel('Câu trả lời tiếng Nhật (text)')).toBeEmpty()
  await answer(page)
  await page.getByLabel('Attempt trước để đối chiếu').selectOption({index:1})
  await expect(page.getByText('KHÔNG SO SÁNH TIẾN BỘ ĐỘC LẬP',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Independent Retry',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Gợi ý Guided Retry'})).not.toBeVisible()
  await expect(page.getByText('直近のプロジェクトで、ご自身が担当した作業を具体的に説明してください。',{exact:true})).toBeVisible()
  await expect(page.getByLabel('Câu trả lời tiếng Nhật (text)')).toBeEmpty()
  await answer(page,'私は入力フォームを担当しました。APIの入力エラーを画面に表示する処理を実装しました。')
  await page.getByLabel('Attempt trước để đối chiếu').selectOption({index:2})
  await expect(page.getByText('CÙNG RUBRIC · Có thể đối chiếu tự đánh giá',{exact:true})).toBeVisible()
  page.once('dialog',d=>d.accept());await page.getByRole('button',{name:'Sửa transcript'}).click()
  await expect(page.getByRole('heading',{name:'Evidence Inspector'})).not.toBeVisible()
  await expect(page.getByText('Điểm tự đánh giá: 67 / 100',{exact:true})).not.toBeVisible()
  await answer(page,'確認済みの担当内容だけ説明します。')
  await expect(page.getByRole('heading',{name:'Transcript v2'})).toBeVisible()
  await expect(page.getByText('Điểm tự đánh giá: N/A',{exact:true})).toBeVisible()
  await page.reload();await openBank(page);await page.getByRole('button',{name:'Lịch sử Interview',exact:true}).click()
  await expect(page.locator('.interview-workspace .history-item')).toHaveCount(3)
})
test('BrSE track offline, safe transcript rendering, backup round-trip and invalid import preservation',async({page,context})=>{
  await page.setViewportSize({width:360,height:800});await page.goto('/')
  await page.evaluate(async()=>{await navigator.serviceWorker.ready});await context.setOffline(true);await page.reload()
  await openBank(page)
  await page.getByLabel('Track luyện tập').selectOption('BRSE')
  await expect(page.getByText('brse-text-v1',{exact:false})).toBeVisible()
  await page.getByRole('article').filter({has:page.getByRole('heading',{name:'Khách yêu cầu đổi phạm vi'})}).getByRole('button').click()
  const text='<img src=x onerror="window.unwanted=true"> 要件と優先度を確認させてください。'
  await answer(page,text)
  await expect(page.getByText('Làm rõ yêu cầu · 35%',{exact:true})).toBeVisible()
  await expect(page.getByTestId('interview-transcript').locator('img')).toHaveCount(0)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.getByRole('button',{name:'Backup Interview',exact:true}).click()
  const pending=page.waitForEvent('download');await page.getByRole('button',{name:'Xuất Interview JSON'}).click();const path=await (await pending).path()
  await page.locator('.interview-workspace input[type=file]').setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from('{"schemaVersion":2}')})
  await expect(page.getByRole('alert')).toContainText('Không nhập được')
  await page.getByRole('button',{name:'Lịch sử Interview',exact:true}).click();await expect(page.locator('.interview-workspace .history-item')).toHaveCount(1)
  await page.getByRole('button',{name:'Backup Interview',exact:true}).click()
  page.once('dialog',d=>d.accept());await page.getByRole('button',{name:'Xóa toàn bộ Interview',exact:true}).click()
  await expect(page.getByRole('status').filter({hasText:'Đã xóa dữ liệu Interview.'})).toBeVisible()
  page.once('dialog',d=>d.accept());await page.locator('.interview-workspace input[type=file]').setInputFiles(path!)
  await expect(page.getByRole('status').filter({hasText:'Đã khôi phục dữ liệu Interview.'})).toBeVisible()
  await page.reload();await openBank(page);await page.getByRole('button',{name:'Lịch sử Interview',exact:true}).click()
  await expect(page.locator('.interview-workspace .history-item')).toHaveCount(1)
  await page.getByRole('button',{name:'Mở feedback & retry'}).click()
  await expect(page.getByTestId('interview-transcript')).toHaveText(text)
  await context.setOffline(false)
})
