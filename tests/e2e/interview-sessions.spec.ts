import {test,expect} from '@playwright/test'
test('three-turn session persists, reports evidence, retries full session and invalidates edited score',async({page})=>{
  await page.goto('/');await page.getByRole('button',{name:'Phỏng vấn & Retry',exact:true}).click()
  await page.getByLabel('Track luyện tập').selectOption('BRSE')
  await page.getByRole('button',{name:'Bắt đầu phiên 3 lượt'}).click()
  const report=page.getByTestId('session-report')
  await expect(report).toContainText('0/3 lượt đã gửi')
  await expect(page.getByRole('button',{name:'Trả lời lượt 2',exact:true})).toBeDisabled()
  await page.reload();await page.getByRole('button',{name:'Phỏng vấn & Retry',exact:true}).click();await page.getByRole('button',{name:'Phiên nhiều lượt',exact:true}).click();await page.getByRole('button',{name:'Mở phiên',exact:true}).click()
  for(let i=1;i<=3;i++){
    await page.getByRole('button',{name:`Trả lời lượt ${i}`,exact:true}).click()
    await page.getByLabel('Câu trả lời tiếng Nhật (text)').fill('要件と影響を確認して、明日ご連絡します。')
    await page.getByRole('button',{name:'Gửi câu trả lời & xem feedback'}).click()
    await expect(page.getByRole('heading',{name:'Evidence Inspector'})).toBeVisible()
    for(const criterion of ['clarify','impact','actions']){
      await page.getByLabel('Tiêu chí rubric').selectOption(criterion)
      await page.getByLabel('Trích dẫn chính xác từ transcript').fill('要件')
      await page.getByLabel('Giải thích điểm & việc cần sửa').fill('Cần xác nhận lại ảnh hưởng với nhóm.')
      await page.getByRole('button',{name:'Lưu tự đánh giá có chứng cứ'}).click()
      await expect(page.getByRole('status').filter({hasText:'Đã lưu tự đánh giá có chứng cứ'})).toBeVisible()
    }
    await page.getByRole('button',{name:'← Báo cáo phiên · chọn lượt tiếp theo',exact:true}).click()
    await expect(report).toContainText(`${i}/3 lượt đã gửi`)
  }
  await expect(report).toContainText('Tự đánh giá toàn phiên: 33 / 100')
  await page.getByRole('button',{name:'Independent Retry toàn phiên',exact:true}).click()
  await expect(report).toContainText('INDEPENDENT');await expect(report).toContainText('0/3 lượt đã gửi')
  await page.getByRole('button',{name:'Trả lời lượt 1',exact:true}).click()
  await expect(page.getByLabel('Câu trả lời tiếng Nhật (text)')).toBeEmpty()
  await expect(page.getByText('Independent Retry: không hiện gợi ý', {exact:false})).toBeVisible()
  await page.getByRole('button',{name:'Phiên nhiều lượt',exact:true}).click()
  await page.getByRole('button',{name:'Mở phiên',exact:true}).last().click()
  await page.getByRole('button',{name:'Mở chứng cứ lượt 1',exact:true}).click()
  page.once('dialog',d=>d.accept());await page.getByRole('button',{name:'Sửa transcript',exact:true}).click()
  await page.getByRole('button',{name:'← Báo cáo phiên · chọn lượt tiếp theo',exact:true}).click()
  await expect(report).toContainText('2/3 lượt đã gửi');await expect(report).toContainText('Tự đánh giá toàn phiên: N/A')
  await page.setViewportSize({width:360,height:800})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
})
